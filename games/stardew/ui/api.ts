// Stardew komutlarının tek giriş noktası (hepsi `stardew_` önekli; bkz. games/stardew/src/commands.rs).

import { invoke } from "@/lib/ipc";
import type { JobSnapshot } from "@/lib/types";
import type {
  Environment,
  FileHash,
  JournalEntry,
  LaunchResult,
  LogReport,
  LookupResult,
  ModsSnapshot,
  NexusCategory,
  NexusModPage,
  NexusSearchPage,
  Profile,
  ProfileDiff,
  SaveBackup,
  SaveInfo,
  StardewSettings,
  TrashMeta,
  UpdateCache,
} from "./types";

export type FolderKind = "mods" | "game" | "saves" | "logs" | "data" | "save-backups" | "trash";

export const api = {
  environment: () => invoke<Environment>("stardew_environment"),
  settings: () => invoke<StardewSettings>("stardew_settings_get"),
  updateSettings: (settings: StardewSettings) => invoke<StardewSettings>("stardew_settings_update", { settings }),
  snapshot: () => invoke<ModsSnapshot>("stardew_get_snapshot"),
  setEnabled: (folders: string[], enabled: boolean) => invoke<JournalEntry>("stardew_set_mods_enabled", { folders, enabled }),
  uninstall: (folders: string[]) => invoke<JournalEntry>("stardew_uninstall_mods", { folders }),
  hashFiles: (folder: string) => invoke<FileHash[]>("stardew_hash_mod_files", { folder }),
  readConfig: (folder: string) => invoke<string | null>("stardew_read_mod_config", { folder }),
  writeConfig: (folder: string, text: string) => invoke<void>("stardew_write_mod_config", { folder, text }),
  installArchive: (rel: string) => invoke<JobSnapshot>("stardew_install_archive", { rel }),
  confirmJob: (id: string, acceptRisk: boolean, options: unknown) => invoke<unknown>("stardew_confirm_job", { id, acceptRisk, options }),
  installSmapi: () => invoke<JobSnapshot>("stardew_install_smapi"),
  checkUpdates: () => invoke<UpdateCache>("stardew_check_updates"),
  lookupMods: (ids: string[]) => invoke<LookupResult[]>("stardew_lookup_mods", { ids }),
  journal: () => invoke<JournalEntry[]>("stardew_list_journal"),
  undo: (id: string) => invoke<JournalEntry>("stardew_undo_journal", { id }),
  trash: () => invoke<TrashMeta[]>("stardew_list_trash"),
  restoreTrash: (id: string) => invoke<JournalEntry>("stardew_restore_trash", { id }),
  deleteTrash: (id: string | null) => invoke<number>("stardew_delete_trash", { id }),
  profiles: () => invoke<Profile[]>("stardew_list_profiles"),
  saveProfile: (input: { id: string | null; name: string; description: string | null; capture: boolean }) => invoke<Profile>("stardew_save_profile", { input }),
  deleteProfile: (id: string) => invoke<void>("stardew_delete_profile", { id }),
  previewProfile: (id: string) => invoke<ProfileDiff>("stardew_preview_profile", { id }),
  applyProfile: (id: string) => invoke<JournalEntry>("stardew_apply_profile", { id }),
  importProfile: (json: string) => invoke<Profile>("stardew_import_profile", { json }),
  saves: () => invoke<SaveInfo[]>("stardew_list_saves"),
  backupSave: (folder: string) => invoke<SaveBackup>("stardew_backup_save", { folder }),
  restoreSave: (folder: string, file: string) => invoke<void>("stardew_restore_save", { folder, file }),
  deleteSaveBackup: (folder: string, file: string) => invoke<void>("stardew_delete_save_backup", { folder, file }),
  log: () => invoke<LogReport>("stardew_read_smapi_log"),
  launch: (vanilla: boolean) => invoke<LaunchResult>("stardew_launch", { vanilla }),
  isRunning: () => invoke<boolean>("stardew_is_running"),
  openPath: (kind: FolderKind, rel?: string | null) => invoke<void>("stardew_open_path", { kind, rel: rel ?? null }),
  nexusSearch: (query: string, sort: string, category: string | null, offset: number) => invoke<NexusSearchPage>("stardew_nexus_search", { query, sort, category, offset }),
  nexusCategories: () => invoke<NexusCategory[]>("stardew_nexus_categories"),
  nexusMod: (modId: number) => invoke<NexusModPage>("stardew_nexus_mod", { modId }),
  installNexus: (modId: number, fileId: number | null, name: string | null) => invoke<JobSnapshot>("stardew_install_nexus", { modId, fileId, name }),
};
